//! Generates `crates/openfga-model/src/generated` from the protos vendored in `codegen/proto`.
//!
//! `cargo run -p codegen` rewrites the generated modules, and `cargo run -p codegen -- --check`
//! fails when a checked-in module differs from a fresh one.
//!
//! `codegen/proto` is `openfga/v1/authzmodel.proto` with its imports, exported from
//! [openfga/api](https://github.com/openfga/api) by
//!
//! ```sh
//! buf export "https://github.com/openfga/api.git#ref=c0650ce2169bcb39a72d73841fb531c200e32248" \
//!     --path openfga/v1/authzmodel.proto -o codegen/proto
//! ```

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use anyhow::{Context, bail};
use prost::Message;
use prost_build::Module;

/// The proto file whose messages form the authorization model.
const MODEL_PROTO: &str = "openfga/v1/authzmodel.proto";

/// The protobuf package of [`MODEL_PROTO`].
const MODEL_PACKAGE: &str = "openfga.v1";

/// What a run does with the freshly generated modules.
enum Mode {
    /// Writes them over the checked-in ones.
    Write,
    /// Fails when a checked-in module differs from a fresh one.
    Check,
}

fn main() -> ExitCode {
    let arguments: Vec<String> = std::env::args().skip(1).collect();
    let mode = match arguments.as_slice() {
        [] => Mode::Write,
        [flag] if flag == "--check" => Mode::Check,
        _ => {
            eprintln!("usage: codegen [--check]");
            return ExitCode::FAILURE;
        }
    };
    match run(&mode) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("codegen: {error:#}");
            ExitCode::FAILURE
        }
    }
}

/// Generates every module and writes or checks it according to `mode`.
fn run(mode: &Mode) -> anyhow::Result<()> {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let output_dir = manifest_dir.join("../crates/openfga-model/src/generated");
    let modules = generate(&manifest_dir.join("proto"))?;
    let mut stale = Vec::new();
    for (file_name, contents) in &modules {
        let path = output_dir.join(file_name);
        match mode {
            Mode::Write => {
                fs::create_dir_all(&output_dir)
                    .with_context(|| format!("creating {}", output_dir.display()))?;
                fs::write(&path, contents)
                    .with_context(|| format!("writing {}", path.display()))?;
            }
            Mode::Check => {
                if fs::read_to_string(&path).ok().as_deref() != Some(contents.as_str()) {
                    stale.push(path);
                }
            }
        }
    }
    if !stale.is_empty() {
        let names: Vec<String> = stale
            .iter()
            .map(|path| path.display().to_string())
            .collect();
        bail!("stale, rerun `cargo run -p codegen`: {}", names.join(", "));
    }
    Ok(())
}

/// Returns each generated module as its file name and contents.
fn generate(proto_root: &Path) -> anyhow::Result<Vec<(PathBuf, String)>> {
    let mut compiler = protox::Compiler::new([proto_root])?;
    compiler.include_imports(true).include_source_info(true);
    compiler.open_file(MODEL_PROTO)?;
    let descriptors = compiler.file_descriptor_set();

    let mut pbjson = pbjson_build::Builder::new();
    pbjson
        .register_descriptors(&descriptors.encode_to_vec())?
        .btree_map(["."]);
    let mut serde = String::from("// This file is @generated by pbjson-build.\n");
    for (_, writer) in pbjson.generate(&[format!(".{MODEL_PACKAGE}")], |_| Ok(Vec::new()))? {
        serde.push_str(&String::from_utf8(writer)?);
    }

    let model_file = descriptors
        .file
        .into_iter()
        .find(|file| file.name() == MODEL_PROTO)
        .with_context(|| format!("{MODEL_PROTO} is missing from the compiled descriptors"))?;
    let mut prost_config = prost_build::Config::new();
    prost_config.btree_map(["."]);
    let types = prost_config
        .generate(vec![(
            Module::from_protobuf_package_name(MODEL_PACKAGE),
            model_file,
        )])?
        .into_values()
        .next()
        .with_context(|| format!("prost-build produced no module for {MODEL_PACKAGE}"))?;

    Ok(vec![
        (PathBuf::from(format!("{MODEL_PACKAGE}.rs")), types),
        (PathBuf::from(format!("{MODEL_PACKAGE}.serde.rs")), serde),
    ])
}
